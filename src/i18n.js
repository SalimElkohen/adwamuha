const DICT = { en, ar };

export function makeT(lang) {
  const d = DICT[lang] || en;
  return (key, vars) => {
    let s = d[key] != null ? d[key] : en[key] != null ? en[key] : key;
    if (vars) Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(String(vars[k])); });
    return s;
  };
}

export function goalTitle(goal, lang, catalogItem) {
  if (goal.catalogId) {
    const c = catalogItem(goal.catalogId);
    if (c) return lang === 'ar' ? c.ar : c.en;
  }
  if (goal.title) return goal.title[lang] || goal.title.en || goal.title.ar;
  return goal.name || '';
}

export function goalDetail(goal, lang, catalogItem, t) {
  const parts = [];
  let target = goal.target, unit = goal.unit;
  if (goal.catalogId && !unit) {
    const c = catalogItem(goal.catalogId);
    if (c) unit = lang === 'ar' ? c.unitAr : c.unitEn;
  }
  if (target) parts.push(target + (unit ? ' ' + unit : ''));
  parts.push(goal.freq === 'weekly' ? t('perWeek', { n: goal.perWeek || 1 }) : t('daily'));
  return parts.join(' · ');
}
